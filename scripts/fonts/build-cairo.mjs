#!/usr/bin/env node
// Build-time only: vendor the OFL-licensed Cairo static font subsets. No CDN at runtime.
// npm ci && node scripts/fonts/build-cairo.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const source = path.join(root, 'node_modules/@fontsource/cairo');
const check = process.argv.includes('--check');
const expected = new Map();
const header = '/* Generated by scripts/fonts/build-cairo.mjs; Cairo, SIL OFL 1.1. */\n';
function cssFor(weights) {
  return header + weights.map(w => fs.readFileSync(path.join(source, `${w}.css`), 'utf8')
    .replace(/, url\([^)]*\.woff\) format\('woff'\)/g, '')
    .replaceAll('./files/', '../fonts/')).join('\n');
}
// Match the weights previously requested by the shared layout. Optional extra
// weights used by the agent are separate, so ordinary pages do not download them.
expected.set('assets/css/cairo.css', cssFor([400, 600, 700, 900]));
expected.set('assets/css/cairo-extra.css', cssFor([500, 800]));
for (const subset of ['arabic', 'latin', 'latin-ext']) {
  for (const weight of [400, 500, 600, 700, 800, 900]) {
    const name = `cairo-${subset}-${weight}-normal.woff2`;
    expected.set(`assets/fonts/${name}`, fs.readFileSync(path.join(source, 'files', name)));
  }
}
expected.set('assets/fonts/Cairo-OFL.txt', fs.readFileSync(path.join(source, 'LICENSE')));
let stale = false;
for (const [rel, content] of expected) {
  const dest = path.join(root, rel);
  const bytes = Buffer.from(content);
  if (fs.existsSync(dest) && fs.readFileSync(dest).equals(bytes)) continue;
  if (check) { console.error(`Stale/missing: ${rel}`); stale = true; }
  else { fs.mkdirSync(path.dirname(dest), { recursive: true }); fs.writeFileSync(dest, bytes); }
}
if (stale) process.exitCode = 1;
else console.log(check ? 'Cairo assets match the pinned package.' : 'Cairo assets generated.');
